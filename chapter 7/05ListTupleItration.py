# how to iterate items of a list using for loop
l = [13, 12, 43, 94, 5, 58, 11, 23, 49]
for item in l:
    print(item)


# how to iterate items of a tuple using for loop
t = (6, 5, 9, 2, 90, 100)
for item in t:
    print(item)


# how to iterate characters of a string using for loops
name = "Sidharth Singh"
for item in name:
    print(item)